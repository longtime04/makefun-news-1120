#!/usr/bin/env python3
"""Copy the pre-drawn front-page image into the output directory.

The image is generated by draw.py and stored next to this file as
entry.png. This script only copies it, so the submitted result is
byte-identical to the reviewed image. Standard library only.

Usage:
    MAKEFUN_OUTPUT_DIR=/path/to/out python3 main.py
If MAKEFUN_OUTPUT_DIR is unset, the image is copied into the
current directory.
"""

import os
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "entry.png"


def main():
    if not SOURCE.exists():
        raise SystemExit("entry.png not found next to main.py; run draw.py first")
    out_dir = Path(os.environ.get("MAKEFUN_OUTPUT_DIR", "."))
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "entry.png"
    shutil.copyfile(SOURCE, target)
    print("wrote", target)


if __name__ == "__main__":
    main()
